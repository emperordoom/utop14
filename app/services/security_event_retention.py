"""Security-event investigative holds and bounded retention orchestration.

Time model
----------
Retention decisions are made on the PostgreSQL clock.  The authoritative
cutoff is read once per run with ``SELECT now()`` and reused for every scope and
batch, so a long run cannot drift.  Run timestamps use ``clock_timestamp()`` in
the database because they describe the actual start/finish of an execution.

Run-log model
-------------
Each batch follows an explicit two-phase protocol:

1. ``begin_retention_run`` records a ``started`` row owned by ``session_user``.
2. ``prune_security_events`` locks that row, deletes eligible events and marks
   the row ``success`` in the same transaction.  A rollback therefore cannot
   leave a success record.

If phase 2 fails, the service rolls back and calls ``abandon_retention_run`` in
a new transaction to mark the row ``failed``.  If the process dies before the
abandon, the row remains ``started`` and is surfaced by the orphan diagnostic.
"""

from __future__ import annotations

import contextlib
import ipaddress
from dataclasses import dataclass
from datetime import datetime, timedelta
from uuid import uuid4

from flask import current_app
from sqlalchemy import func, select, text
from sqlalchemy.engine import Connection, Engine
from sqlalchemy.exc import IntegrityError, SQLAlchemyError

from app.extensions import db
from app.models.security_event import SecurityEvent
from app.models.security_event_retention import (
    RETENTION_SCOPE_FAILURE,
    RETENTION_SCOPE_SUCCESS,
    SecurityEventRetentionHold,
)

_ADVISORY_LOCK_KEY = 0x55544F50313433  # "UTOP143"
_EVENT_LOCK_NAMESPACE = 7381

# The database function accepts only these caller-visible error codes.  Keeping
# the allowlist finite prevents free-text error values in the audit trail.
_ALLOWED_RETENTION_ERROR_CODES = frozenset(
    {
        "DBAPIError",
        "IntegrityError",
        "OperationalError",
        "RuntimeError",
        "SQLAlchemyError",
        "UnknownError",
    }
)


class RetentionError(Exception):
    """Base error for retention and investigative hold operations."""


class RetentionValidationError(RetentionError):
    """Raised when a hold or retention request is invalid."""


class RetentionHoldExists(RetentionError):
    """Raised when an event already has an active investigative hold."""


class RetentionLocked(RetentionError):
    """Raised when another retention run owns the advisory lock."""


class RetentionRunError(RetentionError):
    """Raised when a retention batch or run log operation fails."""


@dataclass(frozen=True, slots=True)
class RetentionPolicy:
    success_days: int
    failure_days: int
    hold_max_days: int
    batch_size: int
    max_batch_size: int
    max_batches: int


@dataclass(frozen=True, slots=True)
class RetentionRunSummary:
    run_id: str
    deleted_count: int
    batch_count: int
    status: str


@dataclass(frozen=True, slots=True)
class OrphanRetentionRun:
    run_id: str
    batch_index: int
    scope: str
    executed_by: str
    started_at: datetime


def retention_policy() -> RetentionPolicy:
    """Resolve and validate the configured retention policy."""
    policy = RetentionPolicy(
        success_days=current_app.config["SECURITY_EVENT_SUCCESS_RETENTION_DAYS"],
        failure_days=current_app.config["SECURITY_EVENT_FAILURE_RETENTION_DAYS"],
        hold_max_days=current_app.config["SECURITY_EVENT_RETENTION_HOLD_MAX_DAYS"],
        batch_size=current_app.config["SECURITY_EVENT_RETENTION_BATCH_SIZE"],
        max_batch_size=current_app.config["SECURITY_EVENT_RETENTION_MAX_BATCH_SIZE"],
        max_batches=current_app.config["SECURITY_EVENT_RETENTION_MAX_BATCHES"],
    )
    if (
        type(policy.success_days) is not int
        or type(policy.failure_days) is not int
        or type(policy.hold_max_days) is not int
        or type(policy.batch_size) is not int
        or type(policy.max_batch_size) is not int
        or type(policy.max_batches) is not int
        or not 90 <= policy.success_days <= 3650
        or not 180 <= policy.failure_days <= 3650
        or not 1 <= policy.hold_max_days <= 3650
        or not 1 <= policy.batch_size <= policy.max_batch_size
        or not 1 <= policy.max_batch_size <= 5000
        or not 1 <= policy.max_batches <= 100
    ):
        raise RetentionValidationError("The configured retention policy is invalid.")
    return policy


def _contains_ip_literal(value: str) -> bool:
    for token in value.replace(",", " ").split():
        candidate = token.strip("[]()")
        try:
            ipaddress.ip_address(candidate)
        except ValueError:
            continue
        return True
    return False


def create_hold(
    *,
    event_id: int,
    reason: str,
    created_by: str,
    duration: timedelta,
) -> int:
    """Create or replace an expired investigative hold for one event.

    The caller supplies a relative ``duration``; ``created_at`` and
    ``expires_at`` are generated by PostgreSQL so they agree with the trigger
    and the retention eligibility check.  Hold creation takes a blocking
    per-event advisory lock (namespace 7381).  The retention function takes the
    matching ``pg_try_advisory_xact_lock`` for each candidate event, so a
    successful hold either commits before retention evaluates the row or causes
    retention to skip that row while the hold transaction still holds the lock.
    This avoids requiring UPDATE privilege on ``security_events`` just to take
    ``FOR UPDATE`` row locks.
    """
    policy = retention_policy()
    if type(event_id) is not int or event_id <= 0:
        raise RetentionValidationError("A valid security event id is required.")
    if not isinstance(reason, str):
        raise RetentionValidationError("A hold reason is required.")
    reason = reason.strip()
    if not reason or len(reason) > 255 or "@" in reason or _contains_ip_literal(reason):
        raise RetentionValidationError("The hold reason is invalid.")
    if not isinstance(created_by, str):
        raise RetentionValidationError("A hold creator is required.")
    created_by = created_by.strip()
    if not created_by or len(created_by) > 120 or "@" in created_by:
        raise RetentionValidationError("The hold creator is invalid.")
    if not isinstance(duration, timedelta):
        raise RetentionValidationError("A valid hold duration is required.")
    if duration <= timedelta(0):
        raise RetentionValidationError("Hold duration must be in the future.")
    if duration > timedelta(days=policy.hold_max_days):
        raise RetentionValidationError("Hold duration exceeds the configured maximum.")

    try:
        # Serialize hold creation against the retention function for this event.
        # The function uses the matching pg_try_advisory_xact_lock namespace/id.
        db.session.execute(
            text("SELECT pg_advisory_xact_lock(:namespace, :event_id)"),
            {"namespace": _EVENT_LOCK_NAMESPACE, "event_id": event_id},
        )
        event = db.session.scalar(select(SecurityEvent).where(SecurityEvent.id == event_id))
        if event is None:
            raise RetentionValidationError("The security event does not exist.")

        # One database-time reference for the active check and the generated
        # timestamps in this transaction.
        db_now = db.session.execute(text("SELECT now()")).scalar_one()

        existing = db.session.scalar(
            select(SecurityEventRetentionHold)
            .where(SecurityEventRetentionHold.security_event_id == event_id)
            .with_for_update()
        )
        if existing is not None and existing.expires_at > db_now:
            raise RetentionHoldExists("The security event already has an active hold.")
        if existing is not None:
            existing.reason = reason
            existing.created_by = created_by
            existing.created_at = func.now()
            existing.expires_at = func.now() + duration
            hold_id = existing.id
        else:
            hold = SecurityEventRetentionHold(
                security_event_id=event_id,
                reason=reason,
                created_by=created_by,
                expires_at=func.now() + duration,
            )
            db.session.add(hold)
            db.session.flush()
            hold_id = hold.id
        db.session.commit()
        return hold_id
    except RetentionError:
        db.session.rollback()
        raise
    except IntegrityError as exc:
        db.session.rollback()
        raise RetentionHoldExists("The security event already has an active hold.") from exc
    except SQLAlchemyError as exc:
        db.session.rollback()
        raise RetentionRunError("Unable to create the investigative hold.") from exc


def _begin_run(
    engine: Engine,
    *,
    run_id: str,
    batch_index: int,
    scope: str,
    cutoff: datetime,
) -> None:
    """Phase 1: commit a ``started`` run-log row."""
    with engine.begin() as connection:
        connection.execute(
            text(
                "SELECT public.begin_retention_run("
                ":scope, :cutoff, CAST(:run_id AS uuid), :batch_index)"
            ),
            {
                "scope": scope,
                "cutoff": cutoff,
                "run_id": run_id,
                "batch_index": batch_index,
            },
        )


def _prune_batch(
    engine: Engine,
    *,
    run_id: str,
    batch_index: int,
    scope: str,
    cutoff: datetime,
    batch_size: int,
) -> int:
    """Phase 2: delete one batch and mark its run-log row ``success``."""
    with engine.begin() as connection:
        return int(
            connection.execute(
                text(
                    "SELECT public.prune_security_events("
                    ":scope, :cutoff, :batch_size, "
                    "CAST(:run_id AS uuid), :batch_index)"
                ),
                {
                    "scope": scope,
                    "cutoff": cutoff,
                    "batch_size": batch_size,
                    "run_id": run_id,
                    "batch_index": batch_index,
                },
            ).scalar_one()
        )


def _abandon_run(
    engine: Engine,
    *,
    run_id: str,
    batch_index: int,
    error_code: str,
) -> None:
    """Mark a still-``started`` row ``failed`` in its own transaction."""
    if error_code not in _ALLOWED_RETENTION_ERROR_CODES:
        error_code = "UnknownError"
    with engine.begin() as connection:
        connection.execute(
            text(
                "SELECT public.abandon_retention_run("
                "CAST(:run_id AS uuid), :batch_index, :error_code)"
            ),
            {
                "run_id": run_id,
                "batch_index": batch_index,
                "error_code": error_code,
            },
        )


def _error_code(exc: BaseException) -> str:
    name = type(exc).__name__
    return name if name in _ALLOWED_RETENTION_ERROR_CODES else "UnknownError"


def _database_now(connection: Connection) -> datetime:
    value = connection.execute(text("SELECT now()")).scalar_one()
    if not isinstance(value, datetime):
        raise RetentionRunError("The database clock could not be read.")
    return value


def run_retention(
    engine: Engine,
    *,
    batch_size: int | None = None,
    max_batches: int | None = None,
) -> RetentionRunSummary:
    """Run bounded retention batches through the approved runner engine.

    The run acquires a session advisory lock, reads PostgreSQL ``now()`` once,
    and uses that single reference for every scope and batch cutoff.  Each batch
    is begun and pruned in separate transactions as described in the module
    docstring.
    """
    if not current_app.config.get("SECURITY_EVENT_RETENTION_ENABLED", True):
        raise RetentionValidationError("Security-event retention is disabled.")

    policy = retention_policy()
    batch_size = policy.batch_size if batch_size is None else batch_size
    max_batches = policy.max_batches if max_batches is None else max_batches
    if type(batch_size) is not int or not 1 <= batch_size <= policy.max_batch_size:
        raise RetentionValidationError("The retention batch size is invalid.")
    if type(max_batches) is not int or not 1 <= max_batches <= 100:
        raise RetentionValidationError("The maximum batch count is invalid.")

    run_id = str(uuid4())
    total_deleted = 0
    total_batches = 0
    last_deleted = 0

    lock_connection = engine.connect()
    try:
        acquired = lock_connection.execute(
            text("SELECT pg_try_advisory_lock(:key)"),
            {"key": _ADVISORY_LOCK_KEY},
        ).scalar()
        if not acquired:
            raise RetentionLocked("Another security-event retention run is active.")

        # One authoritative reference for this run.  ``now()`` is the
        # transaction start time in PostgreSQL and therefore stays constant for
        # every batch that uses this cutoff.
        reference = _database_now(lock_connection)
        cutoffs = {
            RETENTION_SCOPE_SUCCESS: reference - timedelta(days=policy.success_days),
            RETENTION_SCOPE_FAILURE: reference - timedelta(days=policy.failure_days),
        }

        for scope in (RETENTION_SCOPE_SUCCESS, RETENTION_SCOPE_FAILURE):
            cutoff = cutoffs[scope]
            while total_batches < max_batches:
                batch_index = total_batches
                try:
                    _begin_run(
                        engine,
                        run_id=run_id,
                        batch_index=batch_index,
                        scope=scope,
                        cutoff=cutoff,
                    )
                except SQLAlchemyError as exc:
                    raise RetentionRunError(
                        "A security-event retention batch could not be started."
                    ) from exc

                try:
                    last_deleted = _prune_batch(
                        engine,
                        run_id=run_id,
                        batch_index=batch_index,
                        scope=scope,
                        cutoff=cutoff,
                        batch_size=batch_size,
                    )
                except SQLAlchemyError as exc:
                    try:
                        _abandon_run(
                            engine,
                            run_id=run_id,
                            batch_index=batch_index,
                            error_code=_error_code(exc),
                        )
                    except SQLAlchemyError:
                        # The failed-run update itself failed.  Keep the
                        # original batch failure as the cause and expose only a
                        # safe message to the CLI.
                        raise RetentionRunError(
                            "A security-event retention batch failed and the "
                            "failure could not be logged."
                        ) from exc
                    raise RetentionRunError("A security-event retention batch failed.") from exc

                total_batches += 1
                total_deleted += last_deleted
                if last_deleted < batch_size:
                    break

            if total_batches >= max_batches:
                # The batch budget is exhausted.  It is partial when the final
                # scope may still have rows (a full batch was deleted) or when
                # the next policy scope was never evaluated.
                if scope == RETENTION_SCOPE_SUCCESS or last_deleted >= batch_size:
                    return RetentionRunSummary(run_id, total_deleted, total_batches, "partial")
                return RetentionRunSummary(run_id, total_deleted, total_batches, "success")

        return RetentionRunSummary(run_id, total_deleted, total_batches, "success")
    finally:
        try:
            # Closing the connection releases any remaining session lock.  Do
            # not let an unlock failure mask the primary outcome.
            with contextlib.suppress(SQLAlchemyError):
                lock_connection.execute(
                    text("SELECT pg_advisory_unlock(:key)"),
                    {"key": _ADVISORY_LOCK_KEY},
                )
        finally:
            lock_connection.close()


def find_orphan_started_runs(
    engine: Engine,
    *,
    older_than_seconds: int = 3600,
) -> list[OrphanRetentionRun]:
    """Return ``started`` rows older than ``older_than_seconds``.

    These rows indicate a run that died between the begin phase and the prune
    or abandon phase.  They are never success records; operators use this list
    for monitoring and reconciliation.
    """
    if type(older_than_seconds) is not int or not 1 <= older_than_seconds <= 31_536_000:
        raise RetentionValidationError("The orphan age threshold is invalid.")
    with engine.connect() as connection:
        rows = connection.execute(
            text(
                "SELECT run_id, batch_index, scope, executed_by, started_at "
                "FROM public.security_event_retention_runs "
                "WHERE status = 'started' "
                "AND started_at < now() - make_interval(secs => :seconds) "
                "ORDER BY started_at, run_id, batch_index"
            ),
            {"seconds": older_than_seconds},
        ).mappings()
        return [
            OrphanRetentionRun(
                run_id=row["run_id"],
                batch_index=row["batch_index"],
                scope=row["scope"],
                executed_by=row["executed_by"],
                started_at=row["started_at"],
            )
            for row in rows
        ]
